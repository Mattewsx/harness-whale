#!/usr/bin/env python3
"""Build the Harness Whale asset pack written to the ``assets`` data partition.

The pack moves the large, rarely changing image and cue data out of the
application so that two OTA application slots fit in 8 MB Flash. Layout (all
integers little endian):

    0x00  8   magic b"WHALEPAK"
    0x08  u32 format (1)
    0x0C  u32 entry count
    0x10  u32 body offset (0x100)
    0x14  u32 body size
    0x18  32  SHA-256 of the body (the pack identity)
    0x38  24  per entry: name[16] (NUL padded ASCII), u32 offset in body, u32 size
    ...   0xFF padding
    0xFC  u32 CRC-32 of header bytes 0x00..0xFB

Entries are 4-byte aligned inside the body. The same identity is emitted into a
C header so each application image states exactly which pack it was built for.
"""

from __future__ import annotations

import argparse
import hashlib
import struct
import sys
import zlib
from pathlib import Path

MAGIC = b"WHALEPAK"
FORMAT = 1
HEADER_SIZE = 0x100
ENTRY = struct.Struct("<16sII")
FIXED = struct.Struct("<8sIIII32s")
MAX_ENTRIES = (HEADER_SIZE - FIXED.size - 4) // ENTRY.size
MARKER_PREFIX = "WHALE-ASSET-PACK:"


def build(entries: list[tuple[str, bytes]]) -> bytes:
    if not entries or len(entries) > MAX_ENTRIES:
        raise ValueError("asset pack needs 1..%d entries" % MAX_ENTRIES)
    body = bytearray()
    table = []
    for name, data in entries:
        encoded = name.encode("ascii")
        if not encoded or len(encoded) >= 16 or not data:
            raise ValueError(f"invalid asset entry {name!r}")
        while len(body) % 4:
            body.append(0)
        table.append(ENTRY.pack(encoded, len(body), len(data)))
        body += data
    digest = hashlib.sha256(body).digest()
    header = bytearray(b"\xff" * HEADER_SIZE)
    FIXED.pack_into(header, 0, MAGIC, FORMAT, len(entries), HEADER_SIZE, len(body), digest)
    header[FIXED.size:FIXED.size + ENTRY.size * len(table)] = b"".join(table)
    struct.pack_into("<I", header, HEADER_SIZE - 4, zlib.crc32(header[:HEADER_SIZE - 4]))
    return bytes(header) + bytes(body)


def parse(pack: bytes) -> dict[str, object]:
    """Validate a pack exactly as the firmware does and return its fields."""
    if len(pack) < HEADER_SIZE:
        raise ValueError("asset pack is truncated")
    magic, fmt, count, offset, size, digest = FIXED.unpack_from(pack, 0)
    (crc,) = struct.unpack_from("<I", pack, HEADER_SIZE - 4)
    if magic != MAGIC or fmt != FORMAT or offset != HEADER_SIZE:
        raise ValueError("not a Harness Whale asset pack")
    if crc != zlib.crc32(pack[:HEADER_SIZE - 4]):
        raise ValueError("asset pack header CRC mismatch")
    if not 1 <= count <= MAX_ENTRIES or len(pack) < offset + size:
        raise ValueError("asset pack bounds are invalid")
    body = pack[offset:offset + size]
    if hashlib.sha256(body).digest() != digest:
        raise ValueError("asset pack body SHA-256 mismatch")
    entries = {}
    for index in range(count):
        raw, start, length = ENTRY.unpack_from(pack, FIXED.size + index * ENTRY.size)
        name = raw.split(b"\0", 1)[0].decode("ascii")
        if not name or start % 4 or start + length > size or not length:
            raise ValueError(f"asset entry {index} is invalid")
        entries[name] = (start, length)
    return {"sha256": digest.hex(), "size": size, "entries": entries}


def c_header(pack: bytes) -> str:
    info = parse(pack)
    digest = bytes.fromhex(info["sha256"])  # type: ignore[arg-type]
    lines = [
        "/* Generated by tools/make_whale_asset_pack.py. Do not edit. */",
        "#pragma once",
        "#include <stdint.h>",
        f'#define WHALE_ASSET_PACK_SHA256_HEX "{info["sha256"]}"',
        f"#define WHALE_ASSET_PACK_MARKER \"{MARKER_PREFIX}\" WHALE_ASSET_PACK_SHA256_HEX",
        "static const uint8_t whale_asset_pack_sha256[32] = {"
        + ", ".join(f"0x{b:02x}" for b in digest) + "};",
    ]
    for name, (start, length) in info["entries"].items():  # type: ignore[union-attr]
        symbol = name.upper().replace(".", "_").replace("-", "_")
        lines.append(f"#define WHALE_ASSET_{symbol}_OFFSET {start}u")
        lines.append(f"#define WHALE_ASSET_{symbol}_BYTES {length}u")
    return "\n".join(lines) + "\n"


def write_if_changed(path: Path, data: bytes) -> None:
    if path.is_file() and path.read_bytes() == data:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--header", type=Path)
    parser.add_argument("--max-size", type=lambda v: int(v, 0), default=0)
    parser.add_argument("inputs", nargs="+", type=Path)
    args = parser.parse_args(argv)
    entries = [(path.name, path.read_bytes()) for path in args.inputs]
    pack = build(entries)
    if args.max_size and len(pack) > args.max_size:
        print(f"ERROR: asset pack is {len(pack)} bytes; partition is {args.max_size}",
              file=sys.stderr)
        return 1
    write_if_changed(args.output, pack)
    if args.header:
        write_if_changed(args.header, c_header(pack).encode("ascii"))
    print(f"Whale asset pack: {len(pack)} bytes, sha256 {parse(pack)['sha256']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
